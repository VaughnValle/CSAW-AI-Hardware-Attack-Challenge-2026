#!/usr/bin/env python3
"""Recover the supplied circuit, preserving raw output and fixing only its port syntax."""
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
os.chdir(ROOT)
OUT = ROOT / "build/recovered"
OUT.mkdir(parents=True, exist_ok=True)
(ROOT / "rtl").mkdir(exist_ok=True)
commands = []


def run(args, destination):
    commands.append(args)
    with open(destination, "w") as output:
        subprocess.run(args, stdout=output, check=True)


for tool in ("iceunpack", "icebox_vlog", "icebox_explain"):
    if not shutil.which(tool):
        raise SystemExit("Activate OSS CAD Suite before running this script: missing " + tool)

subprocess.run(["iceunpack", "qualifier/ice40_bitstream.bin", str(OUT / "design.asc")], check=True)
commands.append(["iceunpack", "qualifier/ice40_bitstream.bin", str(OUT / "design.asc")])
run(["icebox_vlog", "-l", "-d", "sg48", "-n", "recovered_core", str(OUT / "design.asc")], OUT / "raw.v")
run(["icebox_explain", str(OUT / "design.asc")], OUT / "configuration.txt")
run(["icebox_vlog", "-s", "-l", "-d", "sg48", "-n", "recovered_core", str(OUT / "design.asc")], OUT / "compact_raw.v")

raw = (OUT / "compact_raw.v").read_text()
match = re.search(r"module recovered_core \(([^;]+)\);", raw)
if not match:
    raise SystemExit("Unexpected export header; refusing to rewrite circuit")
declarations = [part.strip() for part in match.group(1).split(",")]
ports = []
for declaration in declarations:
    port = re.fullmatch(r"(input|output|inout)\s+(pin_\d+)", declaration)
    if not port:
        raise SystemExit("Unexpected scalar port declaration: " + declaration)
    ports.append(port.group(2))
# Non-ANSI Verilog permits an output to have a separate reg declaration.
# Icebox's ANSI output plus a later reg declaration causes an Icarus error.
header = "module recovered_core (" + ", ".join(ports) + ");\n"
header += "\n".join(declaration + ";" for declaration in declarations)
normalized = raw[:match.start()] + header + raw[match.end():]
assert normalized.split(";", len(ports) + 1)[-1] == raw[match.end():]
target = ROOT / "rtl/recovered_core.v"
target.write_text("// Generated by scripts/recover.py from the supplied bitstream.\n" + normalized)
manifest = {
    "input": "qualifier/ice40_bitstream.bin",
    "input_sha256": hashlib.sha256((ROOT / "qualifier/ice40_bitstream.bin").read_bytes()).hexdigest(),
    "commands": commands,
    "ports": ports,
    "syntax_normalization": "Convert ANSI scalar port declarations to non-ANSI declarations; circuit body unchanged.",
    "output_sha256": hashlib.sha256(target.read_bytes()).hexdigest(),
}
(OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
print("Recovered", len(ports), "ports into", target.relative_to(ROOT))
